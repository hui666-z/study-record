# 什么是 K-means？（通俗解释）
# ==============================================
"""
K-means 是一种聚类算法，就像给一群人分组一样：

例子：班级里有30个学生，要把他们分成3组
- 不知道他们属于哪一组（没有标签）
- 根据他们的特征（身高、体重、成绩等）自动分组
- 相似的学生会被分到同一组

K-means 的核心思想：
1. K: 要分成几组（簇）
2. means: 每组的中心点（均值点）
3. 算法会自动找到K个中心点，把数据分成K组

与朴素贝叶斯的区别：
- 朴素贝叶斯：分类（有标签，知道每个样本属于哪类）
- K-means：聚类（无标签，自动发现数据的分组）
"""

