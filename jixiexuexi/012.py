print(f"  花瓣长度: {new_sample[0][2]} 厘米")
print(f"  花瓣宽度: {new_sample[0][3]} 厘米")

# 进行预测
prediction = model.predict(new_sample)
prediction_name = iris.target_names[prediction[0]]

# 获取预测概率
proba = model.predict_proba(new_sample)

print(f"\n预测结果:")
