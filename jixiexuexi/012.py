print("""
为什么生成模拟数据？
-------------------
聚类是无监督学习，数据没有标签。
我们生成数据时知道真实的分组，可以验证算法效果。
""")

# make_blobs 参数详解：
# n_samples=300: 生成300个样本
# n_features=2: 每个样本2个特征（便于可视化）
# centers=4: 生成4个簇（中心点）
# cluster_std=0.60: 每个簇的标准差（控制数据的分散程度）
# random_state=42: 随机种子（保证每次运行结果相同）
X_cluster, y_true = make_blobs(
    n_samples=300,      # 300个样本
    n_features=2,       # 每个样本2个特征
    centers=4,          # 4个簇
    cluster_std=0.60,   # 簇的标准差
    random_state=42     # 随机种子
)

# 返回值说明：
# X_cluster: 特征数据，形状 (300, 2)
# y_true: 真实的簇标签（用于验证，算法不知道）

print(f"\n生成的数据信息:")
print(f"  样本数量: {X_cluster.shape[0]}")
print(f"  特征数量: {X_cluster.shape[1]}")
print(f"  真实簇数量: {len(set(y_true))}")

print("\n前5个样本的特征:")
for i in range(5):
    print(f"  样本{i+1}: {X_cluster[i]}")

