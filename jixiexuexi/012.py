print("\n" + "=" * 70)
print("12. 创建并训练 K-means 模型")
print("=" * 70)

print("""
K-means 算法原理：
----------------
1. 随机选择K个点作为初始中心点
2. 将每个样本分配到最近的中心点
3. 重新计算每个簇的中心点（均值）
4. 重复步骤2-3，直到中心点不再变化

就像找聚会地点：
- 每组选一个中心地点
- 大家走到最近的地点
- 根据大家的位置重新调整中心
- 直到大家都满意为止
""")

# 创建 K-means 模型
# n_clusters=4: 分成4个簇
# random_state=42: 随机种子
kmeans = KMeans(n_clusters=4, random_state=42)

print("\n开始训练模型...")
# fit: 训练模型（聚类）
#   - 传入特征数据 X_cluster
#   - 不需要标签（无监督学习）
#   - 算法自动发现数据的分组
